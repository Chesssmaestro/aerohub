def migrate(connection) -> None:
    """Добавляет колонки, появившиеся после создания базы (SQLite не умеет это сам)."""
    from sqlalchemy import text

    for table in Base.metadata.sorted_tables:
        existing = {row[1] for row in connection.execute(text(f'PRAGMA table_info("{table.name}")'))}
        if not existing:
            continue
        for column in table.columns:
            if column.name in existing:
                continue
            ddl = f'{column.name} {column.type.compile(engine.dialect)}'
            default = column.default.arg if column.default is not None and not callable(column.default.arg) else None
            if default is not None:
                literal = f"'{default}'" if isinstance(default, str) else int(default) if isinstance(default, bool) else default
                ddl += f' DEFAULT {literal}'
            connection.execute(text(f'ALTER TABLE "{table.name}" ADD COLUMN {ddl}'))


def import_parts(db: Session) -> int:
    """Загружает каталог запчастей из data/parts.json (обновляет цены и наличие)."""
    path = BASE_DIR / 'data' / 'parts.json'
    if not path.exists():
        return 0

    items = json.loads(path.read_text(encoding='utf-8'))
    existing = {p.external_id: p for p in db.scalars(select(Part)) if p.external_id}
    added = 0
    for item in items:
        part = existing.get(item.get('external_id'))
        if part is None:
            part = Part(external_id=item.get('external_id'), article=item['article'])
            db.add(part)
            added += 1
        part.name = item['name']
        part.article = item['article']
        part.price = item.get('price') or 0
        part.stock = item.get('stock') or 'Под заказ'
        part.group = item.get('group') or 'Прочие узлы'
        part.kind = item.get('kind') or 'Прочее'
        part.models = ','.join(item.get('models') or [])
    db.commit()
    return added


def init_db() -> None:
    """Создаёт таблицы, догоняет схему и наполняет базу при первом запуске."""
    Base.metadata.create_all(engine)
    with engine.begin() as connection:
        migrate(connection)
    db = SessionLocal()
    try:
        if db.query(StaffRole).count() == 0:
            seed_staff_roles(db)
        if db.query(User).count() == 0:
            seed_demo_users(db)
        db.commit()
        import_parts(db)
    finally:
        db.close()
