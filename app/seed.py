        for label, value, red in data['kpi']:
            db.add(StaffKpi(role_id=role.id, label=label, value=value, red_line=red))
        for code, name, result, kpi in data['processes']:
            db.add(StaffProcess(role_id=role.id, code=code, name=name, result=result, kpi=kpi))
